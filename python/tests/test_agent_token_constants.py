"""The `*_AGENT_TOKENS` classes must agree with the tokenizers they name.

Those classes are generated by `scripts/generate_agent_tokens.py` from a table
of `(constant, token, offset)` triples, entirely independently of
`insert_agent_tokens` in `src/core/pretrained.rs`. Two hand-maintained tables
for the same ids is exactly the shape that drifts: adding a bundled vocabulary
without regenerating leaves the class missing, and changing a base id leaves
every constant in it silently wrong — wrong in the worst way, since a constant
is what callers reach for precisely so they do not have to think about the id.

So this asserts the generated constants against `special_token_id` on the loaded
tokenizer, which is the same map `from_pretrained` builds. A constant that does
not match is a generator that was not re-run.
"""

import pytest

import splintr
from splintr import Tokenizer

